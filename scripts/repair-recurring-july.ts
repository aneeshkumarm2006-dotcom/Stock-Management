/**
 * Repairs the client's two recurring-transaction defects, for ONE org.
 *
 *  (A) Un-freezes rules where a backwards `nextDate` edit left
 *      `lastPostedDate >= nextDate`. Such a rule is skipped by the poster
 *      forever while still showing "Active". The fix advances `nextDate`
 *      forward by its frequency until it is past `lastPostedDate`, so the
 *      schedule resumes WITHOUT re-posting a period that already posted.
 *
 *  (B) Promotes the Draft Bills the poster already generated to `Due` and
 *      writes their accrual JE, so they appear on the Bills "Open" tab and
 *      reach Financials — matching what the poster now does at creation time.
 *
 * Dry-run by default. Pass --commit to write.
 *   npx --yes tsx scripts/repair-recurring-july.ts
 *   npx --yes tsx scripts/repair-recurring-july.ts --commit
 */
import dns from 'node:dns';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import mongoose, { Types } from 'mongoose';
import { connectToDatabase } from '../lib/db/mongoose';
import { RecurringTransaction } from '../lib/db/models/pm/RecurringTransaction';
import { Bill } from '../lib/db/models/pm/Bill';
import { advanceNextDate } from '../lib/pm/recurringPoster';
import { postBillToLedger } from '../lib/pm/postBillToLedger';

function loadEnvLocal() {
  try {
    for (const line of readFileSync(resolve('.env.local'), 'utf8').split(/\r?\n/)) {
      const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
      if (m && m[1] && process.env[m[1]] === undefined) process.env[m[1]] = m[2];
    }
  } catch {
    /* optional */
  }
}

const ORG_ID = '6a15a84e5bac3c1113395eb4';
const COMMIT = process.argv.includes('--commit');
const ymd = (x: unknown) =>
  x ? new Date(x as string).toISOString().slice(0, 10) : '—';
const money = (c: number) => `$${(c / 100).toFixed(2)}`;

async function main() {
  loadEnvLocal();
  const servers = process.env.MONGODB_DNS_SERVERS;
  if (servers) dns.setServers(servers.split(',').map((s) => s.trim()));
  await connectToDatabase();
  const orgObjectId = new Types.ObjectId(ORG_ID);

  console.log(`MODE: ${COMMIT ? 'COMMIT (writing)' : 'DRY RUN (no writes)'}`);
  console.log(`ORG:  ${ORG_ID}\n`);

  // ---- (A) frozen rules -------------------------------------------------
  console.log('=== (A) FROZEN RULES ===');
  const rules = await RecurringTransaction.find({
    organizationId: orgObjectId,
    active: true,
    lastPostedDate: { $ne: null },
  });
  let frozen = 0;
  for (const r of rules) {
    if (!r.lastPostedDate) continue;
    if (new Date(r.lastPostedDate) < new Date(r.nextDate)) continue;
    frozen++;
    let next = new Date(r.nextDate);
    let guard = 0;
    while (new Date(r.lastPostedDate) >= next && guard++ < 240) {
      next = advanceNextDate(next, r.frequency);
    }
    console.log(
      `  ${String(r._id)} ${JSON.stringify(r.memo ?? '')}\n` +
        `    lastPosted=${ymd(r.lastPostedDate)}  nextDate ${ymd(r.nextDate)} -> ${ymd(next)}`,
    );
    if (COMMIT) {
      r.nextDate = next;
      await r.save();
    }
  }
  if (!frozen) console.log('  none');

  // ---- (B) draft bills from the poster ----------------------------------
  console.log('\n=== (B) DRAFT BILLS GENERATED BY THE POSTER ===');
  const drafts = await Bill.find({
    organizationId: orgObjectId,
    status: 'Draft',
    createdBy: { $in: ['Recurring bill', 'Recurring check'] },
  }).sort({ invoiceDate: 1 });

  let promoted = 0;
  let totalCents = 0;
  for (const b of drafts) {
    console.log(
      `  ${String(b._id)}  ${ymd(b.invoiceDate)}  ${money(b.amount)}  ${JSON.stringify(b.memo ?? '')}`,
    );
    totalCents += b.amount;
    if (!COMMIT) continue;

    if (b.journalEntryId) {
      console.log('    already has a JE — status flip only');
      b.status = 'Due';
      await b.save();
      promoted++;
      continue;
    }
    const ctx = {
      userId: String(b.createdByUserId ?? orgObjectId),
      orgId: ORG_ID,
      roles: [] as string[],
      impersonatedBy: null,
    };
    try {
      const { journalEntryId } = await postBillToLedger({
        orgId: ORG_ID,
        ctx,
        bill: {
          _id: b._id,
          invoiceDate: b.invoiceDate,
          memo: b.memo,
          vendorId: b.vendorId,
          scopePropertyId:
            b.scope?.type === 'Property' && b.scope.id ? b.scope.id : null,
          lines: b.lines,
          attachmentFileId: b.attachmentFileId,
        },
      });
      b.journalEntryId = journalEntryId;
      b.status = 'Due';
      await b.save();
      promoted++;
      console.log(`    posted JE ${String(journalEntryId)}`);
    } catch (err) {
      console.log(
        `    FAILED: ${err instanceof Error ? err.message : String(err)}`,
      );
    }
  }
  if (!drafts.length) console.log('  none');
  console.log(
    `\n  ${drafts.length} draft bill(s), ${money(totalCents)} total` +
      (COMMIT ? ` — ${promoted} promoted to Due` : ' — would be promoted to Due'),
  );

  if (!COMMIT) console.log('\nDry run only. Re-run with --commit to apply.');
  await mongoose.disconnect();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
